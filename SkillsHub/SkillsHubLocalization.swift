    func localized(_ englishText: String, language: AppLanguage, preferredLanguages: [String]) -> String {
        let resolvedLanguage = language.resolved(preferredLanguages: preferredLanguages)
        guard resolvedLanguage != .english else {
            return englishText
        }
        return Self.uiStrings[resolvedLanguage]?[englishText]
