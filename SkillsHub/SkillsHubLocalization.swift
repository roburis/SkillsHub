import Foundation

nonisolated struct LocalizedMessage: Codable, Hashable, Sendable, ExpressibleByStringLiteral, ExpressibleByStringInterpolation {
    var template: String
    var arguments: [String]
    var isVerbatim: Bool

    init(_ template: String, arguments: [String] = [], isVerbatim: Bool = false) {
        self.template = template
        self.arguments = arguments
        self.isVerbatim = isVerbatim
    }

    init(stringLiteral value: String) {
        self.init(value)
    }

    init(stringInterpolation: StringInterpolation) {
        self.init(stringInterpolation.template, arguments: stringInterpolation.arguments)
    }

    static func verbatim(_ value: String) -> Self {
        Self(value, isVerbatim: true)
    }

    var isEmpty: Bool { template.isEmpty }

    func contains(_ other: String) -> Bool {
        template.contains(other) || arguments.contains { $0.contains(other) }
    }

    struct StringInterpolation: StringInterpolationProtocol {
        var template = ""
        var arguments: [String] = []

        init(literalCapacity: Int, interpolationCount: Int) {
            template.reserveCapacity(literalCapacity + interpolationCount * 2)
            arguments.reserveCapacity(interpolationCount)
        }

        mutating func appendLiteral(_ literal: String) {
            template.append(literal)
        }

        mutating func appendInterpolation<T>(_ value: T) {
            template.append("%@")
            arguments.append(String(describing: value))
        }
    }
}

nonisolated func == (lhs: LocalizedMessage, rhs: String) -> Bool {
    lhs.arguments.isEmpty && lhs.template == rhs
}

nonisolated func == (lhs: String, rhs: LocalizedMessage) -> Bool {
    rhs == lhs
}

