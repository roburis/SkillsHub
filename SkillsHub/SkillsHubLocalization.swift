    }

    func missingUIKeys(for language: AppLanguage) -> [String] {
        let resolvedLanguage = language.resolved(preferredLanguages: ["en"])
        guard resolvedLanguage != .english else { return [] }
        let required = Set(Self.uiStrings[.chinese, default: [:]].keys)
            .union(Self.uiStrings[.japanese, default: [:]].keys)
            .union(Self.supplementalUIStrings[.chinese, default: [:]].keys)
            .union(Self.supplementalUIStrings[.japanese, default: [:]].keys)
        let available = Self.uiStrings[resolvedLanguage, default: [:]]
            .merging(Self.supplementalUIStrings[resolvedLanguage, default: [:]]) { _, supplemental in supplemental }
        return required.filter { available[$0] == nil }.sorted()
    }
