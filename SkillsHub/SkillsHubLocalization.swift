            ?? englishText
    }

    func localized(_ message: LocalizedMessage, language: AppLanguage) -> String {
        let template = message.isVerbatim ? message.template : localized(message.template, language: language)
        return Self.interpolate(template, arguments: message.arguments)
    }

    private static func interpolate(_ template: String, arguments: [String]) -> String {
        guard !arguments.isEmpty else { return template }
        var result = ""
        var argumentIndex = 0
        var index = template.startIndex
        let conversionCharacters = CharacterSet(charactersIn: "@dDiuUxXoOfFeEgGcCsSpaA")

        while index < template.endIndex {
            guard template[index] == "%" else {
                result.append(template[index])
                index = template.index(after: index)
                continue
            }
            let next = template.index(after: index)
            if next < template.endIndex, template[next] == "%" {
                result.append("%")
                index = template.index(after: next)
                continue
            }
            var conversion = next
            while conversion < template.endIndex,
                  String(template[conversion]).rangeOfCharacter(from: conversionCharacters) == nil {
                conversion = template.index(after: conversion)
            }
            guard conversion < template.endIndex, argumentIndex < arguments.count else {
                result.append(template[index])
                index = next
                continue
            }
            result.append(arguments[argumentIndex])
            argumentIndex += 1
            index = template.index(after: conversion)
        }
        return result
    }

